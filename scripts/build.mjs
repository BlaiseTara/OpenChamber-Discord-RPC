import { build } from 'esbuild';
import { readFile, stat } from 'node:fs/promises';

const dev = process.argv.includes('--dev');
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));

const common = {
  bundle: true,
  minify: !dev,
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
  define: {
    'process.env.NODE_ENV': JSON.stringify(dev ? 'development' : 'production'),
  },
};

await build({
  ...common,
  entryPoints: ['src/panel/main.ts'],
  outfile: 'panel/main.js',
  format: 'iife',
  platform: 'browser',
  target: ['chrome120'],
});

await build({
  ...common,
  entryPoints: ['src/service/main.ts'],
  outfile: 'service/main.js',
  format: 'esm',
  platform: 'node',
  target: ['node20'],
  banner: {
    js: `// @openchamber/discord-rpc ${pkg.version} — generated by scripts/build.mjs`,
  },
});

const files = ['panel/main.js', 'service/main.js'];
for (const file of files) {
  const info = await stat(new URL(`../${file}`, import.meta.url));
  console.log(`${file}: ${(info.size / 1024).toFixed(1)} kB`);
}
